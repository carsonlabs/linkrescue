// Generate one SQL paste that publishes multiple content/blog posts into the
// blog_posts CMS (linkrescue's own Supabase project since migration 016).
// Reads frontmatter from each markdown file, strips the leading H1 (the blog
// template renders post.title) and authoring comments, emits dollar-quoted,
// re-runnable INSERT ... ON CONFLICT DO UPDATE statements.
//
//   node scripts/generate-blog-inserts.js
//
// Output: scripts/PUBLISH-PASTE-<date>.sql → paste into the linkrescue
// Supabase SQL Editor (project skclpvjkvlqwvkmffemy).

const fs = require('fs');
const path = require('path');

const POSTS = [
  'best-affiliate-link-checker-2026',
  'silent-revenue-killer',
  'audit-site-link-rot',
];

const BLOG_DIR = path.join(__dirname, '..', 'content', 'blog');
const today = new Date().toISOString().slice(0, 10);
const OUT = path.join(__dirname, `PUBLISH-PASTE-${today}.sql`);

function parseFrontmatter(md) {
  const m = md.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!m) throw new Error('no frontmatter');
  const fm = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w[\w-]*):\s*(.*)$/);
    if (!kv) continue;
    let val = kv[2].trim();
    if (val.startsWith('[')) {
      fm[kv[1]] = JSON.parse(val.replace(/'/g, '"'));
    } else {
      fm[kv[1]] = val.replace(/^"|"$/g, '');
    }
  }
  return { fm, body: md.slice(m[0].length) };
}

function sqlArray(arr) {
  return `ARRAY[${arr.map((t) => `'${String(t).replace(/'/g, "''")}'`).join(',')}]`;
}

function q(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

let out = `-- LinkRescue CMS — publish ${POSTS.length} evergreen posts (${today})
-- Target: linkrescue Supabase project (skclpvjkvlqwvkmffemy) -> SQL Editor
-- Safe to re-run: ON CONFLICT (slug) DO UPDATE. Generated by scripts/generate-blog-inserts.js
`;

for (const slug of POSTS) {
  const raw = fs.readFileSync(path.join(BLOG_DIR, `${slug}.md`), 'utf8');
  const { fm, body } = parseFrontmatter(raw);
  let md = body
    .split('\n')
    .filter((line) => !/^\s*<!--.*-->\s*$/.test(line))
    .join('\n')
    .replace(/^\s*#\s+.*\r?\n+/, '')
    .trim() + '\n';

  const TAG = `$lr_${slug.replace(/-/g, '_').slice(0, 20)}$`;
  if (md.includes(TAG)) throw new Error(`content of ${slug} contains tag ${TAG}`);

  out += `
INSERT INTO blog_posts (
  slug, title, author, tags, category, seo_title, meta_description, content, status, sites, published_at
) VALUES (
  ${q(slug)},
  ${q(fm.title)},
  'Carson Roell',
  ${sqlArray(fm.tags || [])},
  ${q(fm.category || 'affiliate-marketing')},
  ${q(fm.seo_title || fm.title)},
  ${q(fm.meta_description || '')},
  ${TAG}${md}${TAG},
  'published',
  ARRAY['linkrescue'],
  now()
)
ON CONFLICT (slug) DO UPDATE SET
  title = EXCLUDED.title,
  author = EXCLUDED.author,
  tags = EXCLUDED.tags,
  category = EXCLUDED.category,
  seo_title = EXCLUDED.seo_title,
  meta_description = EXCLUDED.meta_description,
  content = EXCLUDED.content,
  status = EXCLUDED.status,
  sites = EXCLUDED.sites,
  published_at = COALESCE(blog_posts.published_at, EXCLUDED.published_at);
`;
}

out += `
-- Verify
SELECT slug, title, status, published_at FROM blog_posts ORDER BY published_at DESC;
`;

fs.writeFileSync(OUT, out, 'utf8');
console.log(`Wrote ${OUT} (${out.length} bytes, ${POSTS.length} posts)`);
