// Generate the SQL to publish the June 2026 Link Rot Index into the blog_posts CMS.
// Reads the rendered markdown, strips the leading H1 (the blog template renders
// post.title as the H1) and any authoring HTML comments, and emits a safe,
// re-runnable dollar-quoted INSERT ... ON CONFLICT DO UPDATE.
//
//   node scripts/generate-index-insert.js
//
// Output: scripts/insert-june-index.sql  → paste into the AgentReady Supabase SQL Editor.

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'content', 'blog', 'link-rot-index-june-2026.md');
const OUT = path.join(__dirname, 'insert-june-index.sql');

let md = fs.readFileSync(SRC, 'utf8');

// Drop standalone authoring comment lines (BEGIN/END GENERATED DATA, provenance).
md = md
  .split('\n')
  .filter((line) => !/^\s*<!--.*-->\s*$/.test(line))
  .join('\n');

// Drop the leading H1 — the template renders the title separately.
md = md.replace(/^#\s+.*\r?\n+/, '');

md = md.trim() + '\n';

const TAG = '$lrindex$';
if (md.includes(TAG)) {
  throw new Error('Content contains the dollar-quote tag; choose a different tag.');
}

const sql = `-- LinkRescue CMS — publish the June 2026 Link Rot Index
-- Target: AgentReady Supabase project (CMS home for the marketing sites) -> SQL Editor
-- Safe to re-run: ON CONFLICT (slug) DO UPDATE. Generated by scripts/generate-index-insert.js
-- Source: content/blog/link-rot-index-june-2026.md (H1 + authoring comments stripped)

INSERT INTO blog_posts (
  slug, title, author, tags, category, seo_title, meta_description, content, status, sites, published_at
) VALUES (
  'link-rot-index-june-2026',
  'The Link Rot Index — June 2026',
  'Carson Roell',
  ARRAY['link rot','affiliate links','data study','link rot index','affiliate marketing'],
  'data',
  'The Link Rot Index — June 2026: 6,550 Affiliate Links Audited',
  'We scanned 50 well-known affiliate sites (683 pages, 6,550 outbound links): 9.1% had broken affiliate attribution, 5.8% were dead or timed out, and 4.7% were bot-blocked. The first monthly public dataset on affiliate link health.',
  ${TAG}${md}${TAG},
  'published',
  ARRAY['linkrescue'],
  '2026-06-15T13:00:00Z'
)
ON CONFLICT (slug) DO UPDATE SET
  title = EXCLUDED.title,
  author = EXCLUDED.author,
  tags = EXCLUDED.tags,
  category = EXCLUDED.category,
  seo_title = EXCLUDED.seo_title,
  meta_description = EXCLUDED.meta_description,
  content = EXCLUDED.content,
  status = EXCLUDED.status,
  sites = EXCLUDED.sites,
  published_at = EXCLUDED.published_at;

-- Verify
SELECT slug, title, status, sites, published_at
FROM blog_posts
WHERE slug = 'link-rot-index-june-2026';
`;

fs.writeFileSync(OUT, sql, 'utf8');
console.log('Wrote ' + OUT + ' (' + sql.length + ' bytes, content ' + md.length + ' chars)');
